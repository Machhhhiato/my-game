export function strategicDirectionOptions(): Record<string,StrategicDirectionOption> {
  const options = Object.entries(content).flatMap(([domain,group])=>group.rows.map((row,index)=>({id:`direction.${domain}.${index+1}`,domain:domain as StrategicDirectionDomain,title:row[0],stance:row[1],summary:row[2],beneficiary:row[3],burdenBearer:row[4],prerequisite:row[5],metrics:{...profiles[row[6]]},consequences:[...row[7]]})));
  return Object.fromEntries(options.map(option=>[option.id,option]));
}

export function initialStrategicDirectionSelections(): Record<StrategicDirectionDomain,StrategicDirectionSelectionState> {
  return Object.fromEntries(Object.keys(content).map(domain=>[domain,{domain,revisionCooldownDays:0}])) as Record<StrategicDirectionDomain,StrategicDirectionSelectionState>;
}

